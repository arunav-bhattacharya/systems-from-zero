/** A quiet local SparkSession: loopback only, 4 shuffle partitions, AQE off so plans stay as planned. */
fun demoSpark(localDir: File? = null): SparkSession =
    SparkSession.builder()
        .appName("sfz-demo")
        .master("local[4]")
        .config("spark.ui.enabled", "false")
        .config("spark.sql.shuffle.partitions", "4")
        .config("spark.sql.adaptive.enabled", "false")
        .config("spark.sql.session.timeZone", "UTC")
        .config("spark.driver.host", "127.0.0.1")
        .config("spark.driver.bindAddress", "127.0.0.1")
        .apply { if (localDir != null) config("spark.local.dir", localDir.absolutePath) }
        .getOrCreate()
        .also { it.sparkContext().setLogLevel("ERROR") }

/** [n] made-up payments in 4 partitions, generated by Spark itself (no files), the same every run. */
fun payments(spark: SparkSession, n: Long = 1_000_000): Dataset<Row> =
    spark.range(0, n, 1, 4).select(
        col("id").alias("payment_id"),
        pmod(hash(col("id")), lit(500)).alias("merchant_id"),
        pmod(hash(col("id"), lit(2)), lit(250_000)).plus(100).cast("bigint").alias("amount_cents"),
    )

/** 500 merchants, one row each. */
fun merchants(spark: SparkSession): Dataset<Row> =
    spark.range(0, 500, 1, 2).select(
        col("id").cast("int").alias("merchant_id"),
        concat(lit("Merchant "), col("id")).alias("merchant_name"),
    )

/** Collects what the scheduler ran: jobs, and per stage its tasks and shuffle traffic. */
class StageLog(private val spark: SparkSession) : SparkListener() {
    data class StageRun(val id: Int, val tasks: Int, val recordsWritten: Long, val bytesWritten: Long, val bytesRead: Long)

    val jobs = CopyOnWriteArrayList<Int>()
    val stages = CopyOnWriteArrayList<StageRun>()

    init {
        spark.sparkContext().addSparkListener(this)
    }

    override fun onJobStart(jobStart: SparkListenerJobStart) {
        jobs += jobStart.jobId()
    }

    override fun onStageCompleted(stageCompleted: SparkListenerStageCompleted) {
        val i = stageCompleted.stageInfo()
        val m = i.taskMetrics()
        stages += StageRun(i.stageId(), i.numTasks(), m.shuffleWriteMetrics().recordsWritten(),
            m.shuffleWriteMetrics().bytesWritten(), m.shuffleReadMetrics().totalBytesRead())
    }

    /** Runs [action] and returns what ran for it. */
    fun <T> run(action: () -> T): Pair<List<Int>, List<StageRun>> {
        spark.sparkContext().listenerBus().waitUntilEmpty()
        jobs.clear()
        stages.clear()
        action()
        spark.sparkContext().listenerBus().waitUntilEmpty()
        return jobs.toList() to stages.sortedBy { it.id }
    }
}

/** The physical plan's lines that name an exchange or a join, with the #ids and plan ids cut. */
fun planLines(df: Dataset<*>, vararg words: String): List<String> =
    df.queryExecution().executedPlan().toString().lines()
        .filter { line -> words.any { it in line } }
        .map { it.replace(Regex("""^[\s:|+-]+"""), "").replace(Regex("""#\d+L?"""), "").replace(Regex(""", \[plan_id=\d+]"""), "") }
