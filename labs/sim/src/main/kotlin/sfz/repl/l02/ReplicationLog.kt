package sfz.repl.l02

import kotlin.random.Random

/**
 * Lesson repl-02: what goes into the replication log. A leader runs statements against a payments
 * table and writes two logs side by side: the statements it ran (statement-based replication) and
 * the rows they changed (row-based, logical replication). Followers replay one log or the other, and
 * the tests compare their tables with the leader's.
 *
 * Each server has its own clock and its own random generator, as real servers do. That is where
 * statement replay goes wrong.
 */

/** One row of the payments table. */
data class Row(
    val id: Long,
    val merchant: String,
    val amountCents: Long,
    val feeCents: Long,
    val ref: String,
    val createdAt: Long,
)

/** A timestamp in a statement: now() on whichever server runs it, or a fixed value. */
sealed interface Ts {
    data object Now : Ts
    data class At(val ms: Long) : Ts
}

/** A payment reference in a statement: a random one, generated by whichever server runs it, or a fixed one. */
sealed interface Ref {
    data object Random : Ref
    data class Fixed(val value: String) : Ref
}

/** A statement, as statement-based replication ships it. [sql] is how it would read in SQL. */
sealed interface Statement {
    val sql: String

    /** INSERT INTO payments (merchant, amount, fee, ref, created_at) VALUES (...): the id comes from the counter. */
    data class Insert(val merchant: String, val amountCents: Long, val ref: Ref = Ref.Random, val createdAt: Ts = Ts.Now) : Statement {
        override val sql: String
            get() {
                val r = when (ref) { Ref.Random -> "md5(random()::text)"; is Ref.Fixed -> "'${ref.value}'" }
                val t = when (createdAt) { Ts.Now -> "now()"; is Ts.At -> "${createdAt.ms}" }
                return "INSERT INTO payments (merchant, amount, fee, ref, created_at) VALUES ('$merchant', $amountCents, 0, $r, $t)"
            }
    }

    /** UPDATE payments SET fee = fee + cents WHERE merchant = ...: relative to whatever is there. */
    data class AddFee(val merchant: String, val cents: Long) : Statement {
        override val sql: String get() = "UPDATE payments SET fee = fee + $cents WHERE merchant = '$merchant'"
    }

    /** DELETE FROM payments WHERE merchant = ... LIMIT n, with no ORDER BY: whichever n rows the scan meets first. */
    data class DeleteSome(val merchant: String?, val limit: Int) : Statement {
        override val sql: String
            get() = "DELETE FROM payments${merchant?.let { " WHERE merchant = '$it'" } ?: ""} LIMIT $limit"
    }
}

/** One change to one row, as row-based (logical) replication ships it. */
sealed interface RowEvent {
    val id: Long

    /** A new row: every column's value. */
    data class Inserted(val row: Row) : RowEvent {
        override val id: Long get() = row.id
    }

    /** A changed row: its key and every column's new value. */
    data class Updated(val row: Row) : RowEvent {
        override val id: Long get() = row.id
    }

    /** A removed row: only its key. */
    data class Deleted(override val id: Long) : RowEvent
}

