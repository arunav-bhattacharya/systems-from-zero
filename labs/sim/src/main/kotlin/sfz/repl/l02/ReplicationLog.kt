/**
 * The leader (given): it runs each statement and writes both logs. With [pinValues] it first
 * calls [pin], so the statement it runs and logs carries its own now() and random values.
 */
class Leader(clockMs: () -> Long, seed: Long) : Server("leader", clockMs, seed) {
    val statementLog: MutableList<Statement> = mutableListOf()
    val rowLog: MutableList<RowEvent> = mutableListOf()
    var pinValues: Boolean = false

    fun run(statement: Statement) {
        val toRun = if (pinValues) pin(statement, this) else statement
        val before = rows.toMap()
        execute(toRun)
        statementLog += toRun
        rowLog += rowEvents(before, rows)
    }

    /**
     * Two sessions insert at the same time: [first] takes its id first, but [second] commits first
     * (given). Both logs are written in commit order, as a binlog or WAL is.
     */
    fun runInterleaved(first: Statement.Insert, second: Statement.Insert) {
        val a = if (pinValues) pin(first, this) as Statement.Insert else first
        val b = if (pinValues) pin(second, this) as Statement.Insert else second
        val before = rows.toMap()
        execute(a)
        val afterA = rows.toMap()
        execute(b)
        statementLog += b                                   // second committed first
        statementLog += a
        rowLog += rowEvents(afterA, rows)
        rowLog += rowEvents(before, afterA)
    }
}

