/**
 * One database server with its own clock and random generator (given, apart from [applyRow]).
 *
 * [rows] is in heap order, the order a scan without ORDER BY meets the rows: an insert goes at the
 * end, and an update writes the new row version at the end, as PostgreSQL's heap does.
 */
open class Server(val name: String, private val clockMs: () -> Long, seed: Long) {
    val random: Random = Random(seed)
    val rows: LinkedHashMap<Long, Row> = linkedMapOf()

    /** The id the next insert gets. */
    var nextId: Long = 1

    /** now() on this server. */
    fun now(): Long = clockMs()

    /** md5(random()::text) on this server, shortened to 8 hex digits. */
    fun randomRef(): String = "%08x".format(random.nextInt())

    /** Runs [statement] here, with this server's clock, random generator, counter and heap order (given). */
    fun execute(statement: Statement) {
        when (statement) {
            is Statement.Insert -> {
                val id = nextId++
                val ref = when (val r = statement.ref) { Ref.Random -> randomRef(); is Ref.Fixed -> r.value }
                val at = when (val t = statement.createdAt) { Ts.Now -> now(); is Ts.At -> t.ms }
                rows[id] = Row(id, statement.merchant, statement.amountCents, 0, ref, at)
            }
            is Statement.AddFee -> {
                val matching = rows.values.filter { it.merchant == statement.merchant }
                for (row in matching) {
                    rows.remove(row.id)                                    // the new version goes to the end
                    rows[row.id] = row.copy(feeCents = row.feeCents + statement.cents)
                }
            }
            is Statement.DeleteSome -> {
                rows.values.filter { statement.merchant == null || it.merchant == statement.merchant }
                    .take(statement.limit)
                    .forEach { rows.remove(it.id) }
            }
        }
    }

    /** Loads a dump: the rows in id order, as a restore writes them into a fresh heap (given). */
    fun loadDump(dump: Collection<Row>) {
        rows.clear()
        dump.sortedBy { it.id }.forEach { rows[it.id] = it }
        nextId = (dump.maxOfOrNull { it.id } ?: 0) + 1
    }

    /** Statement-based replication: run every statement again, here (given). */
    fun replayStatements(log: List<Statement>) = log.forEach(::execute)

    /** Row-based replication: apply every row event, here (given). */
    fun replayRows(log: List<RowEvent>) = log.forEach(::applyRow)

